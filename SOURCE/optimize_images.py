"""Optimise quiz images for fast loading, and emit blur placeholders (LQIP).

Three jobs:
  1. Drop unreferenced files (orphan PNGs left over from the AI generation runs).
  2. Downscale + recompress every referenced image to the size it is actually
     displayed at, as progressive JPEG.
  3. Write js/quiz-lqip.js: a tiny base64 blur for each image, inlined so the
     card never shows an empty box while the real file streams in.

Idempotent: re-running on already-optimised files is a no-op (they are already
under the width cap and the recompress is skipped if it would not help).
"""
import base64, io, json, os, re, sys

from PIL import Image, ImageFilter

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
QUIZ = os.path.join(BASE, "scorm-quiz")
IMG_ROOT = os.path.join(QUIZ, "assets", "images")
DATA_JS = os.path.join(QUIZ, "js", "quiz-data.js")
LQIP_JS = os.path.join(QUIZ, "js", "quiz-lqip.js")

# Displayed sizes: the scene image spans the card (~550px CSS, 2x for retina);
# option thumbnails are a 4:3 tile in a 2x2 grid (~240px CSS, 2x). Going wider
# than this ships pixels the learner never sees.
SCENE_MAX_W = 1100
OPTION_MAX_W = 480
QUALITY = 72
LQIP_W = 16


def referenced():
    """Every assets/images/... path the quiz actually asks for."""
    src = open(DATA_JS, encoding="utf-8").read()
    return set(re.findall(r"assets/images/[^\"']+", src))


def optimise(path, max_w):
    before = os.path.getsize(path)
    im = Image.open(path)
    if im.mode in ("RGBA", "LA", "P"):
        im = im.convert("RGB")
    if im.width > max_w:
        h = round(im.height * max_w / im.width)
        im = im.resize((max_w, h), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=QUALITY, optimize=True, progressive=True)
    if buf.tell() < before:
        with open(path, "wb") as f:
            f.write(buf.getvalue())
        return before, buf.tell(), im.size
    return before, before, im.size


def lqip(path):
    """A 20px-wide blurred JPEG, base64'd — a few hundred bytes."""
    im = Image.open(path).convert("RGB")
    h = max(1, round(im.height * LQIP_W / im.width))
    im = im.resize((LQIP_W, h), Image.LANCZOS).filter(ImageFilter.GaussianBlur(1))
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=30, optimize=True)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()


def main():
    refs = referenced()
    print(f"{len(refs)} images referenced by quiz-data.js")

    # 1. orphans
    freed = 0
    for root, _, files in os.walk(IMG_ROOT):
        for name in files:
            if not name.lower().endswith((".png", ".jpg", ".jpeg", ".webp")):
                continue
            full = os.path.join(root, name)
            rel = os.path.relpath(full, QUIZ).replace("\\", "/")
            if rel not in refs:
                freed += os.path.getsize(full)
                os.remove(full)
                print(f"  orphan removed: {rel}")
    print(f"orphans freed: {freed/1048576:.1f} MB")

    # 2 + 3. optimise and measure
    total_before = total_after = 0
    lqips, dims = {}, {}
    for rel in sorted(refs):
        full = os.path.join(QUIZ, rel.replace("/", os.sep))
        if not os.path.exists(full):
            print(f"  MISSING {rel}")
            continue
        max_w = OPTION_MAX_W if "/options/" in rel else SCENE_MAX_W
        b, a, size = optimise(full, max_w)
        total_before += b
        total_after += a
        lqips[rel] = lqip(full)
        dims[rel] = list(size)
        if b != a:
            print(f"  {rel}: {b//1024}KB -> {a//1024}KB  {size[0]}x{size[1]}")

    with open(LQIP_JS, "w", encoding="utf-8") as f:
        f.write("/* Generated by SOURCE/optimize_images.py — do not edit by hand.\n")
        f.write(" * Tiny blurred stand-ins shown instantly while the real image loads,\n")
        f.write(" * plus intrinsic dimensions so the layout never jumps.\n */\n")
        f.write("var QUIZ_LQIP = " + json.dumps(lqips, indent=0) + ";\n\n")
        f.write("var QUIZ_IMG_DIMS = " + json.dumps(dims, indent=0) + ";\n")

    print(f"\nimages: {total_before/1048576:.1f} MB -> {total_after/1048576:.1f} MB "
          f"({100 - total_after*100//max(total_before,1)}% smaller)")
    print(f"total saved incl. orphans: {(total_before - total_after + freed)/1048576:.1f} MB")
    print(f"wrote {LQIP_JS} ({os.path.getsize(LQIP_JS)//1024} KB)")


if __name__ == "__main__":
    main()
